export function getScenarioResponse(input: string): { response: string; followUp?: string } | null {
  for (const scenario of scenarioResponses) {
    if (scenario.keywords.some(keyword => input.includes(keyword))) {
      const response = scenario.responses[Math.floor(Math.random() * scenario.responses.length)];
      const followUp = scenario.followUp ? scenario.followUp[Math.floor(Math.random() * scenario.followUp.length)] : undefined;
      return { response, followUp };
    }
  }
  return null;
}

